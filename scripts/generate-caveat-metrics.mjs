/** Measure the approved Caveat Latin face for deterministic 0.2.8 layout. */
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';

const font = readFileSync(new URL('../packages/render/assets/fonts/caveat-latin.woff2', import.meta.url))
  .toString('base64');
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const metrics = await page.evaluate(async (base64) => {
    const face = new FontFace('Coral Lowfi Caveat', `url(data:font/woff2;base64,${base64})`, { weight: '400 700' });
    await face.load();
    document.fonts.add(face);
    const canvas = document.createElement('canvas');
    const context = canvas.getContext('2d');
    if (!context) throw new Error('Canvas text metrics unavailable');
    const codepoints = [...Array(224).keys()].map((index) => index + 32)
      .concat([305, 338, 339, 710, 730, 732, 8211, 8212, 8216, 8217, 8218, 8220, 8221, 8222,
        8226, 8230, 8249, 8250, 8260, 8364, 8482, 8722, 8725]);
    const result = {};
    const ink = {};
    for (const weight of [400, 500, 550, 700]) {
      context.font = `${weight} 1000px "Coral Lowfi Caveat"`;
      const advances = {};
      ink[weight] = {};
      for (const codepoint of codepoints) {
        const glyph = context.measureText(String.fromCodePoint(codepoint));
        advances[codepoint] = Number((glyph.width / 1000).toFixed(4));
        ink[weight][codepoint] = [Number((glyph.actualBoundingBoxAscent / 1000).toFixed(4)),
          Number((glyph.actualBoundingBoxDescent / 1000).toFixed(4))];
      }
      const vertical = context.measureText('gyp');
      result[weight] = { unitsPerEm: 1000, ascent: vertical.fontBoundingBoxAscent / 1000,
        descent: vertical.fontBoundingBoxDescent / 1000, fallback: 0.6, advances };
    }
    return { result, ink };
  }, font);
  writeFileSync(new URL('../packages/render/src/text/caveat-metrics028.ts', import.meta.url),
    `/** GENERATED by scripts/generate-caveat-metrics028.mjs; do not edit. */\n` +
    `export const CAVEAT_METRICS_028 = ${JSON.stringify(metrics.result)} as const;\n`);
  writeFileSync(new URL('../packages/render/src/text/caveat-ink028.ts', import.meta.url),
    `/** GENERATED by scripts/generate-caveat-metrics028.mjs from the bundled face. */\n` +
    `export const CAVEAT_INK_028 = ${JSON.stringify(metrics.ink)} as const;\n`);
  process.stdout.write('Measured Caveat Latin advances at 400, 500, 550, and 700.\n');
} finally {
  await browser.close();
}
