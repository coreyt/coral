/**
 * Bundle @coral-viz/browser into one ESM file and one IIFE (`Coral`).
 *
 * Exact build-time rewrites keep the bundles within R-061:
 * - portable font faces the default render path cannot reach keep their
 *   metrics but carry a sentinel instead of font data (budget; render refuses
 *   SVG that references the sentinel);
 * - GraphIR 3 uses semantic validation; its unused schema compiler is stubbed.
 *   Successor validation uses an ahead-of-time compiled exact schema, keeping
 *   Core's structural, local and catalog verification without runtime codegen;
 * - ELK's GWT module stops creating `window.goog`, a global nothing reads.
 * Each rewrite fails the build if its target is not found exactly.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createSuccessorBrowserBinding028 } from './successorBrowserBinding028.mjs';
import { build } from 'rolldown';

const packageRoot = resolve(import.meta.dirname, '..');
const manifest = JSON.parse(readFileSync(resolve(packageRoot, 'package.json'), 'utf8'));
const UNAVAILABLE_FACE = 'coral-browser:unavailable-face';
const KEPT_FACES = new Set(['sans:400', 'sans:700']);
const ELK_GLOBAL = '$wnd.goog=$wnd.goog||{};$wnd.goog.global=$wnd.goog.global||$wnd;';

const renderDist = dirname(fileURLToPath(import.meta.resolve('@coral-viz/render')));
const fontModulePath = resolve(renderDist, 'text/generated-fonts.js');
const { GENERATED_FONT_ASSETS } = await import(pathToFileURL(fontModulePath).href);
const reducedFonts = Object.fromEntries(Object.entries(GENERATED_FONT_ASSETS).map(([id, { metrics, source, data400, data700 }]) => [id, {
  metrics,
  ...(KEPT_FACES.has(`${id}:400`) ? { source } : {}),
  data400: KEPT_FACES.has(`${id}:400`) ? data400 : UNAVAILABLE_FACE,
  data700: KEPT_FACES.has(`${id}:700`) ? data700 : UNAVAILABLE_FACE,
}]));
const generatedDirectory = resolve(packageRoot, 'build');
mkdirSync(generatedDirectory, { recursive: true });
const reducedFontModule = resolve(generatedDirectory, 'generated-fonts.js');
// The variable Inter font supplies both weights. Share its exact bytes rather
// than serializing duplicate literals beyond gzip's 32 KiB backreference window.
const fontData = new Map();
const fontReference = (data) => {
  if (!fontData.has(data)) fontData.set(data, `fontData${fontData.size}`);
  return fontData.get(data);
};
const sansMetricsLiteral = JSON.stringify(GENERATED_FONT_ASSETS.sans.metrics);
const fontRecords = Object.entries(reducedFonts).map(([id, { data400, data700, source }]) => {
  return `${JSON.stringify(id)}:{metrics:sansMetrics,${source ? `source:${JSON.stringify(source)},` : ''}data400:${fontReference(data400)},data700:${fontReference(data700)}}`;
});
writeFileSync(reducedFontModule, `/** GENERATED by packages/browser/scripts/build.mjs: Inter 400/700; Caveat is bundled separately. */\n` +
  `const sansMetrics=${sansMetricsLiteral};\n` +
  [...fontData].map(([data, name]) => `const ${name}=${JSON.stringify(data)};`).join('\n') +
  `\nexport const GENERATED_FONT_ASSETS = {${fontRecords.join(',')}};\n`);

const successorBinding = createSuccessorBrowserBinding028(generatedDirectory);
const successorValidatorModule = successorBinding.validatorModule;

// Rolldown reports native ids; compare them with POSIX separators.
const posix = (id) => id?.replaceAll('\\', '/');
const AJV_STUB = '\0coral-browser:ajv-stub';
const SCHEMA_STUB = '\0coral-browser:schema-stub';
let elkRewritten = false;
let successorRewritten = false;
let caveatSourceRewritten = false;
const fontsModulePosix = posix(resolve(renderDist, 'text/fonts.js'));
const CAVEAT_SOURCE_RE = /\n\s*source:\s*\{\s*packageName:\s*'Caveat Latin variable'[\s\S]*?metricsSha256:\s*'generated-by-scripts\/generate-caveat-metrics028\.mjs',\s*\},/;
const rewrites = {
  name: 'coral-browser-rewrites',
  resolveId(source, importer) {
    // Unused migration exports compile old schemas at module initialization.
    // They are not part of the browser API; avoid retaining their initialization
    // solely for side effects. A live import still has to pass the CSP gates.
    if (['./skills/migrate.js', './skills/successor-migrate.js'].includes(source) &&
      posix(importer)?.endsWith('/@graph-ir/core/dist/index.js'))
      return { id: resolve(dirname(importer), source), moduleSideEffects: false };
    // The Core root also exports Node-only snapshot helpers. Their unused
    // builtin imports have no browser side effects; if a helper becomes live,
    // its named builtin imports remain and the external-import gate below fails.
    if (['fs', 'path'].includes(source) && posix(importer)?.endsWith('/@graph-ir/core/dist/testing/snapshot.js'))
      return { id: source, external: true, moduleSideEffects: false };
    if (source === 'ajv/dist/2020.js' && posix(importer)?.endsWith('/@graph-ir/core/dist/validation/ir-validator.js')) return AJV_STUB;
    if (source === '../schemas/graph-ir.schema.json' && posix(importer)?.endsWith('/@graph-ir/core/dist/validation/ir-validator.js')) return SCHEMA_STUB;
    if (source === './generated-fonts.js' && posix(importer) === posix(resolve(renderDist, 'text/fonts.js'))) return reducedFontModule;
    // Internal @coral-viz/render and @coral-viz/language submodules have no
    // browser import side effects; tree-shake unreachable character/writer/ruleset modules.
    if (importer && source.startsWith('.') && (posix(importer).includes('/packages/render/dist/') || posix(importer).includes('/packages/language/dist/'))) {
      return { id: resolve(dirname(importer), source), moduleSideEffects: false };
    }
    return null;
  },
  load(id) {
    if (id === AJV_STUB) {
      return 'export default class Ajv2020 { compile() { const validate = () => { throw new Error("coral.browser.validation.unsupported: GraphIR 3 schema validation is unavailable in the semantic browser path"); }; validate.errors = null; return validate; } }';
    }
    if (id === SCHEMA_STUB) return 'export default {};';
    return null;
  },
  transform(code, id) {
    const successorCode = successorBinding.transform(code, id);
    if (successorCode !== null) {
      successorRewritten = true;
      return successorCode;
    }
    if (posix(id) === fontsModulePosix) {
      if (!CAVEAT_SOURCE_RE.test(code)) throw new Error(`Expected Caveat build-time provenance block in ${id}.`);
      caveatSourceRewritten = true;
      return code.replace(CAVEAT_SOURCE_RE, '');
    }
    if (!posix(id).endsWith('/elkjs/lib/elk.bundled.js')) return null;
    elkRewritten = true;
    const count = code.split(ELK_GLOBAL).length - 1;
    if (count !== 1) throw new Error(`Expected the ELK window.goog statement once in ${id}; found ${count}.`);
    return code.replace(ELK_GLOBAL, '');
  },
  buildEnd() {
    const seen = new Set(this.getModuleIds());
    for (const required of [AJV_STUB, SCHEMA_STUB, reducedFontModule, successorValidatorModule]) {
      if (!seen.has(required)) throw new Error(`Build rewrite target was not used: ${required}`);
    }
    if (!elkRewritten) throw new Error('The ELK window.goog rewrite did not run.');
    if (!successorRewritten) throw new Error('The successor standalone validator binding did not run.');
    if (!caveatSourceRewritten) throw new Error('The Caveat build-time provenance rewrite did not run.');
  },
};

const banner = `/*! ${manifest.name} ${manifest.version} | Apache-2.0 | bundles elkjs (EPL-2.0), canonicalize (Apache-2.0), @graph-ir/core, @noble/hashes, ajv runtime helpers, fast-deep-equal and libavoided-js (MIT), Inter and Caveat (OFL-1.1); see THIRD_PARTY_NOTICES.md */`;

// One module graph: the IIFE is the ESM text with its single export clause
// turned into a return value, so the ESM never loads more bytes.
const esmFile = resolve(packageRoot, 'dist/coral-browser.js');
const bundled = await build({
  cwd: packageRoot,
  input: resolve(packageRoot, 'src/index.ts'),
  platform: 'browser',
  plugins: [rewrites],
  logLevel: 'warn',
  output: { file: esmFile, format: 'esm', minify: true, codeSplitting: false, sourcemap: false },
});
const imports = bundled.output.filter((item) => item.type === 'chunk')
  .flatMap((chunk) => [...chunk.imports, ...chunk.dynamicImports]);
if (imports.length) throw new Error(`Browser bundle has external imports: ${imports.join(', ')}`);
// Audit rendered code, rather than modules merely visited before tree shaking.
const runtimePackages = new Set();
const renderedModules = new Set();
for (const chunk of bundled.output.filter((item) => item.type === 'chunk')) {
  for (const [id, module] of Object.entries(chunk.modules)) {
    if (!module.renderedLength) continue;
    renderedModules.add(posix(id));
    const match = [...posix(id).matchAll(/\/node_modules\/((?:@[^/]+\/)?[^/]+)\//g)].at(-1);
    if (match && !match[1].startsWith('@coral-viz/')) runtimePackages.add(match[1]);
  }
}
for (const id of [successorBinding.coreModule, successorValidatorModule])
  if (!renderedModules.has(posix(id))) throw new Error(`Required successor validation was not emitted: ${id}`);
writeFileSync(resolve(generatedDirectory, 'bundled-packages.json'), `${JSON.stringify([...runtimePackages].sort(), null, 2)}\n`);
const esm = readFileSync(esmFile, 'utf8').trimEnd();
const exportClause = /export\{([^{}]*)\};?$/.exec(esm);
if (!exportClause || esm.slice(0, exportClause.index).includes('export{') || /\bimport\s*[{*\w]/.test(esm.slice(0, 200))) {
  throw new Error('The ESM bundle must end in exactly one export clause and import nothing.');
}
const members = exportClause[1].split(',').map((entry) => {
  const [local, exported = local] = entry.split(/\s+as\s+/);
  return `${exported}:${local}`;
});
const body = esm.slice(0, exportClause.index);
writeFileSync(esmFile, `${banner}\n${esm}\n`);
writeFileSync(resolve(packageRoot, 'dist/coral-browser.iife.js'),
  `${banner}\nvar Coral=(function(){"use strict";${body}return Object.freeze({${members.join(',')}})})();\n`);
