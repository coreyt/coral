/* eslint-disable no-control-regex -- the quoted-token rules reject control code points. */
/**
 * Coral 0.2.8 saved-document core for syntax tooling and executable parity
 * checks. The TypeScript header and candidate readers own semantic validity,
 * recovery, source ranges, and profile-specific meaning. This grammar is not
 * a second runtime reader or a published replacement for tree-sitter-coral.
 * Edition 0.2.9 adds @symbol definitions and port label and maxConnections;
 * the external scanner (scanner.c) owns raw artwork blocks, so no grammar
 * rule tokenizes raw content. Edition gating stays with the TypeScript reader.
 */
const secondEnds = ['#|>', '|#>', '|>#', '#<>', '<#>', '<>#', '#o', 'o#',
  '#>', '>#', '|>', '<>', 'o', '|', '{', '>'];
const solid = ['-', '--', '---', '----', '-----', '------'].flatMap((shaft) =>
  ['', ...secondEnds].map((end) => shaft + end));
const dashed = ['-.-', '-.--', '-.---', '-.----'].flatMap((shaft) =>
  ['', ...secondEnds].map((end) => shaft + end));
const reverse = ['-', '--', '---', '----', '-----', '------'].flatMap((shaft) =>
  [`<${shaft}`, `<${shaft}>`]);
const ends = ['none', 'arrow', 'filledArrow', 'triangle', 'filledTriangle',
  'diamond', 'filledDiamond', 'circle', 'filledCircle', 'bar', 'crowFoot',
  'zeroOrOne', 'one', 'zeroOrMany', 'oneOrMany', 'zeroToMany'];

module.exports = grammar({
  name: 'coral',
  extras: () => [/[ \t]/],
  externals: $ => [$.raw_block],
  conflicts: $ => [[$.prelude_trivia, $.trivia_line], [$.spatial_constraint,$.identifier],
    // A compartment's authored ID may itself be attributes or operations.
    [$.compartment, $.identifier],
    // Trivia between the directives and the first definition belongs to either run.
    [$.source_file]],
  rules: {
    source_file: $ => seq(repeat($.trivia_line), $.diagram_line,
      repeat(choice($.prelude_trivia, $.directive_line)),
      repeat(choice($.symbol_definition, $.prelude_trivia)),
      // A last definition may end the document without a line ending, but
      // only when no body statement follows it.
      choice(alias($._symbol_definition_block, $.symbol_definition), seq(
        repeat(choice($.trivia_line, $.statement_line,
          seq($.route_block, $._newline),
          seq($.sequence_fragment, $._newline),
          seq($.sequence_activation, $._newline), seq($.sequence_region, $._newline),
          seq($.sequence_group, optional($.comment), $._newline))),
        optional(choice($._final_statement, $.route_block, $.sequence_fragment, $.sequence_activation,
          $.sequence_region, seq($.sequence_group, optional($.comment))))))),
    diagram_line: $ => seq(token(/@diagram[ \t]+/), $.diagram_type,
      optional($.diagram_attributes), $._newline),
    diagram_type: () => /[A-Za-z][A-Za-z0-9-]*/,
    diagram_attributes: $ => seq('[', $.diagram_attribute,
      repeat(seq(',', $.diagram_attribute)), ']'),
    diagram_attribute: $ => seq($.identifier, ':',
      choice($.identifier, $.quoted)),
    directive_line: $ => seq(choice(
      seq(token(choice(/@coralVersion[ \t]+/, /@profileVersion[ \t]+/,
        /@catalogVersion[ \t]+/)), $.quoted),
      seq(token(/@conformanceLevel[ \t]+/), choice('none', 'typical', 'strict')),
    ), $._newline),
    symbol_definition: $ => seq($._symbol_definition_block, $._newline),
    _symbol_definition_block: $ => seq(token(/@symbol[ \t]+/), $.identifier, '{',
      optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.symbol_line, $.symbol_artwork)),
      '}', optional($.comment)),
    symbol_line: $ => seq(choice(
      seq(choice('name', 'description', 'source', 'license'), $.quoted),
      seq('tags', repeat1($.quoted)),
      seq('size', $.coordinate, 'x', $.coordinate),
      seq('label', $.placement_side),
      seq('outline', choice('rectangle', 'rounded', 'ellipse', 'diamond')),
      seq('tint', choice('none', 'stroke')),
      $.symbol_anchor, $.port,
    ), optional($.comment), $._newline),
    symbol_anchor: $ => seq('anchor', $.identifier, '[', $.anchor_field,
      repeat(seq(',', $.anchor_field)), ']'),
    anchor_field: $ => choice(
      seq(choice('side', 'exit'), ':', $.side_name),
      seq(choice('at', 'x', 'y'), ':', $.coordinate),
    ),
    side_name: () => choice('N', 'E', 'S', 'W'),
    // raw_block runs from the opening quotes through a line that is exactly
    // three double quotes; scanner.c matches it without interpreting content.
    symbol_artwork: $ => seq('artwork', 'svg', $.raw_block, $._newline),
    statement_line: $ => seq(choice($.node, $.edge, $.arrangement, $.spatial_constraint, $.layout, $.sequence_note),
      optional($.comment), $._newline),
    _final_statement: $ => seq(choice($.node, $.edge, $.arrangement, $.spatial_constraint, $.layout, $.sequence_note),
      optional($.comment)),
    trivia_line: $ => seq(optional($.comment), $._newline),
    prelude_trivia: $ => seq(optional($.comment), $._newline),
    comment: () => token(/\/\/[^\r\n]*/),

    node: $ => seq($.identifier, choice($.node_kind, seq('=', $.node_kind)),
      optional($.node_fields), optional($.label), optional($.node_label_placement),
      optional($.node_position), optional('pinned'), optional($.node_body)),
    node_kind: $ => $.identifier,
    node_position: $ => seq('@', '(', $.coordinate, ',', $.coordinate, ')'),
    coordinate: () => token(/-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?/),
    node_fields: $ => seq('[', $.node_field,
      repeat(seq(',', $.node_field)), ']'),
    node_field: $ => seq(choice('symbol', 'variant', 'conformanceException'),
      ':', $.quoted),
    label: $ => seq(token(/as[ \t]+/), $.quoted),
    placement_side: () => choice('above', 'below', 'left', 'right', 'center'),
    node_label_placement: $ => seq('label', $.placement_side,
      optional(seq('offset', $.coordinate))),
    edge_label_placement: $ => seq('label', $.placement_side,
      optional(seq('at', $.coordinate)), optional(seq('offset', $.coordinate))),
    node_body: $ => choice(
      seq('{', '}'),
      seq('{', optional($.comment), $._newline,
        repeat(choice($.trivia_line, $.body_line,
          seq($.route_block, $._newline))), '}'),
    ),
    body_line: $ => seq(
      choice($.port, $.node, $.edge, $.arrangement, $.spatial_constraint, $.compartment),
      optional($.comment), $._newline),
    port: $ => seq($.identifier, 'port',
      '[', $.port_field,
      repeat(seq(',', $.port_field)), ']'),
    port_field: $ => choice(
      seq('direction', ':', choice('in', 'out', 'inout')),
      seq('anchor', ':', $.identifier),
      seq('label', ':', $.quoted),
      seq('maxConnections', ':', $.positive_integer),
    ),
    positive_integer: () => /[1-9][0-9]*/,

    edge: $ => seq(optional(seq($.identifier, '=')),
      $.endpoint, $.connector, $.endpoint,
      optional($.edge_fields), optional($.label), optional($.edge_label_placement)),
    route_block: $ => seq(token(/route[ \t]+edge[ \t]+/), $.node_reference, '{',
      optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.route_waypoint_line)), '}'),
    route_waypoint_line: $ => seq($.identifier, '=', 'waypoint',
      choice('at', seq('relative', 'to', choice('first', 'second',
        seq('node', $.node_reference), seq('port', $.port_reference), seq('waypoint', $.identifier)), 'offset')),
      '(', $.coordinate, ',', $.coordinate, ')', optional($.comment), $._newline),
    endpoint: $ => seq($.node_reference,
      optional(seq(':', $.identifier))),
    port_reference: $ => seq($.node_reference, ':', $.identifier),
    node_reference: $ => seq($.identifier, repeat(seq('.', $.identifier))),
    connector: () => token(seq(/[ \t]+/, choice(...dashed, ...solid, ...reverse), /[ \t]+/)),
    edge_fields: $ => seq('[',
      choice(seq($.bare_type, optional(seq(',', $.keyed_edge_field,
        repeat(seq(',', $.keyed_edge_field))))),
      seq($.keyed_edge_field,
        repeat(seq(',', $.keyed_edge_field)))),
      ']'),
    bare_type: $ => $.identifier,
    keyed_edge_field: $ => choice(
      seq('type', ':', $.identifier),
      seq('label', ':', $.quoted),
      seq(choice('firstPort', 'secondPort'), ':', $.identifier),
      seq(choice('firstEnd', 'secondEnd'), ':', $.end_name),
      seq('style', ':', $.style_value),
    ),
    end_name: () => choice(...ends),
    style_value: $ => choice($.identifier, $.rgb_hex, $.double_quoted),
    rgb_hex: () => /#[0-9A-Fa-f]{6}/,
    double_quoted: () => token(/"(?:[^"\\\x00-\x1f\x7f-\x9f\u2028-\u2029]|\\["\\n])*"/),

    arrangement: $ => seq(optional(seq($.identifier, '=')),
      'arrange', choice('row', 'column'), ':',
      $.rectangle_member, ',', $.rectangle_member,
      repeat(seq(',', $.rectangle_member)), optional($.constraint_parameters)),
    rectangle_member: $ => choice($.typed_rectangle, $.node_reference),
    typed_rectangle: $ => choice(seq(choice('node','group','edge'), $.node_reference), seq('label',choice('node','edge'),$.node_reference)),
    spatial_constraint: $ => seq('constraint', $.identifier, ':', $.typed_rectangle,
      choice(seq(choice('above','below',seq('left','of'),seq('right','of')),$.typed_rectangle),
      seq('at','the',choice('top','bottom','left','right'),'of',choice('diagram',seq('group',$.node_reference)))),optional($.constraint_parameters)),
    constraint_parameters: $ => seq('[',$.constraint_parameter,repeat(seq(',',$.constraint_parameter)),']'),
    constraint_parameter: $ => choice('required','preferred',seq(choice('gap','inset'),':',$.coordinate),seq('alignment',':',choice('start','center','end')),seq('direction',':',choice('forward','reverse'))),
    layout: $ => seq('layout','[',$.layout_parameter,repeat(seq(',',$.layout_parameter)),']'),
    layout_parameter: $ => choice(seq('algorithm',':',choice('layered','mrtree','stress','force','radial','box','fixed')),seq('direction',':',choice('UP','DOWN','LEFT','RIGHT')),seq('edgeRouting',':',choice('ORTHOGONAL','POLYLINE','SPLINES')),seq(choice('nodeNode','nodeEdge','edgeEdge','layerSpacing'),':',$.coordinate)),
    sequence_note: $ => seq(optional(seq($.identifier, '=')),
      'note', $.quoted, 'on', $.identifier,
      repeat(seq(',', $.identifier))),
    compartment: $ => choice(
      seq(optional(seq($.identifier, '=')), 'attributes', choice(
        seq('{', '}'),
        seq('{', optional($.comment), $._newline,
          repeat(choice($.trivia_line, $.attribute_line)), '}'),
      )),
      seq(optional(seq($.identifier, '=')), 'operations', choice(
        seq('{', '}'),
        seq('{', optional($.comment), $._newline,
          repeat(choice($.trivia_line, $.operation_line)), '}'),
      )),
    ),
    attribute_line: $ => seq($.attribute,
      optional($.comment), $._newline),
    attribute: $ => choice(
      seq('+', $.identifier, ':', $.identifier),
      seq($.identifier, '=', choice('public', 'private', 'protected', 'package'),
        'attribute', $.identifier, ':', $.identifier),
    ),
    operation_line: $ => seq($.operation,
      optional($.comment), $._newline),
    operation: $ => choice(
      seq(token(/[+\-#~][ \t]+/), $.operation_signature),
      seq($.identifier, '=', choice('public', 'private', 'protected', 'package'),
        'operation', $.operation_signature),
    ),
    operation_signature: $ => seq($.identifier, '(',
      optional(seq($.operation_parameter, repeat(seq(',', $.operation_parameter)))),
      ')', optional(seq(':', $.identifier))),
    operation_parameter: $ => seq($.identifier, ':', $.identifier),

    sequence_fragment: $ => choice($.alt_fragment, $.par_fragment, $.guarded_fragment),
    alt_fragment: $ => seq(
      optional(seq($.identifier, '=')),
      token(/alt[ \t]+/), $.quoted, '{',
      optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
        seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
        seq($.sequence_region, $._newline))),
      '}', token(/[ \t]+else[ \t]+/), $.quoted,
      '{', optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
        seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
        seq($.sequence_region, $._newline))),
      repeat(seq('}', token(/[ \t]+else[ \t]+/), $.quoted,
        '{', optional($.comment), $._newline,
        repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
          seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
          seq($.sequence_region, $._newline))))),
      '}', optional($.comment)),
    par_fragment: $ => seq(
      optional(seq($.identifier, '=')),
      token(/par[ \t]+/), optional($.quoted), '{',
      optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
        seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
        seq($.sequence_region, $._newline))),
      '}', token(/[ \t]+and[ \t]+/), optional($.quoted),
      '{', optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
        seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
        seq($.sequence_region, $._newline))),
      repeat(seq('}', token(/[ \t]+and[ \t]+/), optional($.quoted),
        '{', optional($.comment), $._newline,
        repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
          seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
          seq($.sequence_region, $._newline))))),
      '}', optional($.comment)),
    guarded_fragment: $ => seq(
      optional(seq($.identifier, '=')),
      choice(seq(token(/(?:opt|break)[ \t]+/), $.quoted),
        seq(token(/(?:loop|critical)[ \t]+/), optional($.quoted))), '{',
      optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
        seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
        seq($.sequence_region, $._newline))),
      '}', optional($.comment)),
    sequence_activation: $ => seq(optional(seq($.identifier, '=')),
      token(/activation[ \t]+/), $.identifier, '{', optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
        seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
        seq($.sequence_region, $._newline))),
      '}', optional($.comment)),
    sequence_region: $ => seq(optional(seq($.identifier, '=')),
      token(/region[ \t]+/), optional($.quoted), '{', optional($.comment), $._newline,
      repeat(choice($.trivia_line, $.sequence_message_line, $.sequence_note_line,
        seq($.sequence_fragment, $._newline), seq($.sequence_activation, $._newline),
        seq($.sequence_region, $._newline))),
      '}', optional($.comment)),
    sequence_group: $ => seq(optional(seq($.identifier, '=')),
      token(/participants[ \t]+/), $.identifier, repeat(seq(',', $.identifier)),
      optional(seq('[', 'label', ':', $.quoted, ']'))),
    sequence_message_line: $ => seq($.edge,
      optional($.comment), $._newline),
    sequence_note_line: $ => seq($.sequence_note,
      optional($.comment), $._newline),

    identifier: () => choice(/[A-Za-z_][A-Za-z0-9_]*/, 'constraint','layout','node','edge','group','label','attributes','operations',
      'name','description','source','license','tags','size','outline','tint','anchor','artwork'),
    quoted: () => token(choice(
      /"(?:[^"\\\x00-\x1f\x7f-\x9f\u2028-\u2029]|\\["\\n])*"/,
      /'(?:[^'\\\x00-\x1f\x7f-\x9f\u2028-\u2029]|\\['\\n])*'/,
    )),
    _newline: () => /\r?\n/,
  },
});
